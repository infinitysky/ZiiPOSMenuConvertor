def t(key: str, lang: str = "en") -> str:
    """Get translated string for key in given language."""
    return STRINGS.get(lang, STRINGS["en"]).get(key, key)


def lang_display_name(code: str, ui_lang: str = "en") -> str:
    """Get display name for a language code in the current UI language."""
    key = f"lang_{code}"
    return t(key, ui_lang)
